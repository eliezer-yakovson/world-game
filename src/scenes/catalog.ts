import type { StrengthMap } from '../core/types';

export interface Beat {
  t: number;
  say: string;
  emote?: string;
  props?: string[];
  /** Right, then forward, in the direction the player is facing. */
  at?: [number, number];
  cast?: Array<[string, number, number]>;
}

export interface FollowUp {
  id: string;
  label: string;
  beats: Beat[];
  awards?: Partial<StrengthMap>;
}

export interface SceneScript {
  id: string;
  title: string;
  intro: string;
  beats: Beat[];
  follows: FollowUp[];
}

function b(
  say: string,
  emote = 'talk',
  props?: string[],
  at?: [number, number],
  cast?: Array<[string, number, number]>,
): Beat {
  return { t: 3.5, say, emote, props, at, cast };
}

function follow(id: string, label: string, beats: Beat[], awards: Partial<StrengthMap>): FollowUp {
  return { id, label, beats, awards };
}

